/**
 * Writes src/data/resumeQr.ts: the QR code printed in the resume PDF's
 * masthead, as one SVG path of its dark modules. `npm run qr`.
 *
 * Generated rather than drawn at runtime so the browser ships no QR encoder
 * for a mark only paper ever shows. The path carries no colour: the page
 * fills it with `currentColor`, so the code is inked by a theme token like
 * everything else.
 *
 * The URL carries the same `utm_source=resume-pdf` the rest of the PDF
 * traffic uses, with `utm_medium=qr` so a scan is distinguishable from a
 * typed visit in the CRM. tests/resume.test.ts checks it against
 * `contact.site`, so a domain change fails there instead of on paper.
 */
import QRCode from 'qrcode'
import { readFileSync, writeFileSync } from 'node:fs'

const URL = 'https://eric.sh/resume?utm_source=resume-pdf&utm_medium=qr'
const OUT = new globalThis.URL('../src/data/resumeQr.ts', import.meta.url)

// M: recovers from ~15% damage, which a folded or creased page needs, at a
// density that still prints comfortably under an inch wide.
const { modules } = QRCode.create(URL, { errorCorrectionLevel: 'M' })
const { size, data } = modules

// One rectangle per horizontal run of dark modules, rather than one per
// module: a third the path length, and no hairline seams between neighbours
// when a PDF viewer antialiases each rectangle separately.
let path = ''
for (let y = 0; y < size; y++) {
  for (let x = 0; x < size; ) {
    if (!data[y * size + x]) { x++; continue }
    let run = 1
    while (x + run < size && data[y * size + x + run]) run++
    path += `M${x} ${y}h${run}v1h-${run}z`
    x += run
  }
}

const source = `// Generated by scripts/generate-qr.mjs. Do not edit by hand: run \`npm run qr\`.

/** The resume PDF's QR code: \`path\` draws the dark modules in a \`size\` × \`size\` viewBox, no quiet zone. */
export const resumeQr = {
  url: ${JSON.stringify(URL)},
  size: ${size},
  path: ${JSON.stringify(path)},
} as const
`

let current = ''
try { current = readFileSync(OUT, 'utf8') } catch { /* first run */ }
if (current === source) {
  console.log(`resumeQr.ts unchanged (${size}×${size})`)
} else {
  writeFileSync(OUT, source)
  console.log(`wrote resumeQr.ts (${size}×${size}, ${path.length} chars of path)`)
}
