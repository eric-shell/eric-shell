/**
 * Regenerates src/lib/displayKerning.ts from public/fonts/display.woff2.
 *
 *   npm run kerning
 *
 * Headings that animate letter by letter (RiseText) render each letter in its
 * own inline-block, and an inline-block boundary ends the font's kerning: the
 * pair table in the font is simply never consulted. RiseText restores it with a
 * per-letter margin read from the table this writes.
 *
 * The values are measured, not typed: each pair's width in Chromium with
 * `font-kerning: normal`, minus the two glyphs measured alone. Only non-zero
 * pairs are kept. Re-run after replacing the font.
 */
import { chromium } from 'playwright'
import { readFileSync, writeFileSync } from 'node:fs'

const CHARS = [...'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789&.,\'’!?-:+']
const font = readFileSync(new URL('../public/fonts/display.woff2', import.meta.url)).toString('base64')

const browser = await chromium.launch()
const page = await browser.newPage()
await page.setContent(`<style>@font-face{font-family:D;src:url(data:font/woff2;base64,${font}) format('woff2')}</style>`)
const pairs = await page.evaluate(async (chars) => {
  await document.fonts.load('1000px D')
  const ctx = document.createElement('canvas').getContext('2d')
  ctx.font = '1000px D'
  ctx.fontKerning = 'normal'
  const w = t => ctx.measureText(t).width
  const out = {}
  for (const a of chars) for (const b of chars) {
    const k = Math.round(w(a + b) - w(a) - w(b))
    if (k) out[a + b] = k
  }
  return out
}, CHARS)
await browser.close()

const body = Object.entries(pairs).map(([k, v]) => `  ${JSON.stringify(k)}: ${v},`).join('\n')
writeFileSync(new URL('../src/lib/displayKerning.ts', import.meta.url), `// Generated by scripts/display-kerning.mjs from public/fonts/display.woff2.
// Do not edit by hand: run \`npm run kerning\` after changing the font.

/** The font's own kerning, in thousandths of an em, for every non-zero pair. */
export const DISPLAY_KERNING: Record<string, number> = {
${body}
}

/** Even tracking for every Display heading, in em. Matches \`.tracking-display\`. */
export const DISPLAY_TRACKING = -0.02

/** Space after letter \`a\` when \`b\` follows it: the font's kerning plus the even tracking, in em. */
export function displayGap(a: string, b: string): number {
  return (DISPLAY_KERNING[a.toUpperCase() + b.toUpperCase()] ?? 0) / 1000 + DISPLAY_TRACKING
}
`)
console.log(`wrote ${Object.keys(pairs).length} pairs`)
